// Локальные классы-константы для экранов программ и тренировок.
//
// Макеты Figma 954:1545 / 932:1941 / 1006:2005 / 916:2586 / 1039:2066 /
// 1042:2892 переиспользуют один и тот же набор форм. Держим их в одном месте,
// чтобы значения не расходились между экранами, но НЕ выносим в shared/ui —
// это зона других агентов, а паттерны пока подтверждены только на программах
// и тренировках. Если позже они появятся ещё где-то, отсюда легко поднять.
//
// Только семантические токены тем: без #hex, bg-white/black, text-white/black.

/** Пояснительная плашка над контентом (52px, радиус 14px).
 *  Figma 1006:2012 / 932:1948 / 916:2593 — одинаковая на всех экранах блока.
 *  Обводка в макете — нейтральный 600, что в тёмной теме и есть `--line`;
 *  берём тематический `border-line`, иначе в светлой теме рамка не
 *  инвертируется вместе со шкалой. */
export const hintBox =
  'flex min-h-[52px] w-full items-center justify-center rounded-[14px] border border-line px-[22px] py-[10px] text-center text-body-s text-content';

/** Карточка-строка со списочным содержимым: радиус 14px, padding 10px
 *  (Figma 957:1565 / 1006:2031 / 932:1969 / 916:2614). Обводка в макете —
 *  нейтральный 300; в коде это `border-line` по той же причине, что выше:
 *  тематический алиас вместо фиксированной ступени. */
export const outlineCard = 'w-full rounded-[14px] border border-line p-[10px] text-left';

/** Тот же контейнер, но подсвеченный акцентом — «Все упражнения» (957:1608)
 *  и карточка текущего упражнения в тренировке (1039:2066). */
export const outlineCardBrand = 'w-full rounded-[14px] border border-brand-400 p-[10px] text-left';

/** Левая полоса у альтернативного упражнения — «Ан - Фиол.» #C96EFF из макета
 *  это токен серии графиков 4 (design-system.md «Серии графиков»), а не
 *  trainer-500 (#8b5cf6 — другой цвет). Полоса — обводка на карточке, то есть
 *  случай «цвет как текст/контур», поэтому берём тематический `chart-4-text`
 *  (в светлой теме сам chart-4 проваливается до 2.58:1). */
export const altRail = 'w-full border-l border-chart-4-text pl-[10px]';

/** Таб-пилюля списка программ (954:1559 / 954:1561): залитая, радиус 14px.
 *  Активная — заливка акцентом, поверх неё текст берём из `chart-1-fg`
 *  (парный foreground акцента, стабилен между темами — как и сама заливка).
 *  Неактивная — нейтральная заливка `card-light`, текст обычный `content`. */
export function listTab(active: boolean): string {
  return [
    // `basis-0` и общая min-height: каждой пилюле ровно половина ширины, а
    // высота задана парой, а не длиной подписи. Без основы `flex-1` делит
    // только свободное место, и «Стандартные программы» выходили бы шире и выше
    // «Моих программ».
    'flex min-h-[44px] flex-1 basis-0 items-center justify-center rounded-[14px] px-[12px] py-[10px] text-center text-body-s',
    active ? 'bg-brand-400 text-chart-1-fg' : 'bg-card-light text-content',
  ].join(' ');
}

/** Пилюля выбора (день / тренирующийся): прозрачная, обводка меняется по
 *  выбору — 1006:2016 (выбран, акцент) vs 1006:2021 (не выбран, нейтральная). */
export function choicePill(selected: boolean): string {
  return [
    'flex flex-1 items-center justify-center rounded-[14px] border p-[10px] text-body-m text-content',
    selected ? 'border-brand-400' : 'border-line',
  ].join(' ');
}

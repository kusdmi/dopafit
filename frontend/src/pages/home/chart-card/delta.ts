/**
 * Подпись изменения за период у графиков Главной (макет 392:2101 / 392:2170).
 *
 * В макете это ДВЕ строки, а не одна: крупно — изменение в единицах измерения
 * («-2.5 кг», «+10 кг»), под ним мельче — процент со стрелкой («↓ 3%»,
 * «↑ 16.7%»). Раньше выводился только процент, и по графику нельзя было
 * понять, о каких величинах речь.
 */

/** Направление изменения: им же красятся и подпись, и линия графика. */
export type DeltaTone = 'up' | 'down' | 'neutral';

/**
 * Цвет тона как CSS-значение — для линии графика.
 *
 * В макете (392:2090 / 392:2159) линия и подпись изменения ВСЕГДА одного
 * цвета: падение веса зелёное и там, и там, рост силы — оранжевый. Цвет задаёт
 * НАПРАВЛЕНИЕ, а не карточка, поэтому у графика не может быть собственной
 * фиксированной палитры — иначе зелёная подпись оказывается над оранжевой
 * линией.
 *
 * Пара к TONE_CLASS в ChartCard.tsx: одна таблица тонов в двух формах (класс
 * для текста, значение для SVG). Расходиться они не должны.
 */
export const TONE_COLOR: Record<DeltaTone, string> = {
  up: 'var(--color-brand-400)',
  down: 'var(--color-chart-3)',
  neutral: 'var(--color-muted)',
};

/** Абсолютное изменение: последняя точка минус первая — та же база, по которой
 *  backend считает change_percent (domain/rules.ts changePercent), поэтому
 *  знак у обеих строк всегда совпадает. Меньше двух точек — изменения нет. */
export function changeAbs(points: { value: number }[]): number | null {
  if (points.length < 2) return null;
  return points.at(-1)!.value - points[0]!.value;
}

/**
 * «-2.5 кг». Знак ставится всегда, в том числе «+» у роста: подпись читается
 * как изменение, а не как текущее значение. Дробная часть округляется до
 * десятых и отбрасывается, если пустая («+10 кг», а не «+10.0 кг»).
 */
export function formatAbs(value: number, unit: string): string {
  const rounded = Math.round(value * 10) / 10;
  // Округление может дать «-0» — знак у нуля бессмысленен.
  const safe = rounded === 0 ? 0 : rounded;
  const sign = safe > 0 ? '+' : '';
  return `${sign}${safe} ${unit}`;
}

/**
 * «↓ 3%». Стрелка дублирует знак, чтобы направление читалось без опоры на
 * цвет (цвет здесь несёт тот же смысл и не может быть единственным носителем).
 * Модуль процента берётся потому, что направление уже сказано стрелкой:
 * «↓ -3%» читалось бы как двойное отрицание.
 */
export function formatPercent(percent: number): string {
  if (percent === 0) return '0%';
  return `${percent > 0 ? '↑' : '↓'} ${Math.abs(percent)}%`;
}

/**
 * Содержимое онбординга — мотивационные слайды первого запуска.
 *
 * Список, а не один захардкоженный экран: в макете (392:1951) слайд пока один,
 * но экран задуман как слайдер, и добавление второго должно быть правкой ЭТОГО
 * массива, а не разметки. Всё, что меняется от слайда к слайду, лежит здесь;
 * `OnboardingPage` ничего не знает о конкретных цитатах и картинках.
 */
export interface OnboardingSlide {
  /** Стабильный ключ слайда: react-key и, в будущем, аналитика показов. */
  id: string;
  /** Путь к картинке в `public/`. */
  image: string;
  /**
   * Альт картинки. Пустая строка — осознанный выбор для декоративных фото:
   * скринридер пропустит `<img>`, а не зачитает бессмысленное имя файла.
   * Если картинка начнёт нести смысл — сюда придёт описание.
   */
  imageAlt: string;
  /** Цитата, H1. Строки — намеренные переносы из макета. */
  quote: string[];
  /** Подпись под цитатой, H3. */
  subtitle: string[];
}


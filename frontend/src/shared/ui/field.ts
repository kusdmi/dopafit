// Единый источник правды геометрии полей ввода в общем дизайн-коде.
// Все поля (фасад Input на IonItem, Select, нативные <input type="date">/<select>/
// текстовые поля в модалках конструктора) должны визуально СОВПАДАТЬ по высоте,
// радиусу, рамке и фону на одном экране.
//
// Каноническая геометрия — Figma 756:1712 (экран антропометрии, узлы
// 756:1986/757:1991 и далее): обводка 1px нейтральный 500, радиус 14px,
// высота 52px, padding 10px 22px. Совпадает с фасадом Input/Select.
// `neutral-500` — алиас Tailwind-токена на приватную переменную темы
// `--neutral-500` (см. `@theme` в index.css), поэтому обводка задаётся
// готовым классом `border-neutral-500`, без arbitrary value.
//
// Обводка волосяная (1px), а не 2px из DS-узла поля (392:5036): при 12 полях
// подряд (антропометрия) двойная толщина читается раньше значения. Контраст от
// толщины не зависит: `--neutral-500` (#6E6A64) против фона даёт 3.61:1 в
// тёмной теме и 4.91:1 в светлой — обе выше порога 3:1 для нетекстовой графики.
//
// Используются только семантические токены тем (border-neutral-500 / bg-card /
// text-content / text-muted) — без хардкода цветов.

// Геометрия поля без фона и горизонтального padding (высота/радиус/рамка) —
// переиспользуется и в Select, и в fieldClass, чтобы значения были из одного места.
// Фон (bg-card у нативных полей, bg-transparent у stacked-label) и горизонтальный
// padding (px-[22px] обычно, pl-4/pr-9 под кастомную стрелку Select) задаются
// отдельно, но высота, радиус и рамка совпадают везде.
export const fieldGeometry = 'min-h-[52px] rounded-[14px] border border-neutral-500';

// Полный класс для нативных контролов ввода (<input>, <select>), которые НЕ
// проходят через фасад shared/ui/Input.tsx (date-пикеры, select'ы, числовые/
// текстовые поля в модалках конструктора). Та же геометрия, что у Input/Select.
export const fieldClass = `${fieldGeometry} bg-card px-[22px] text-content placeholder:text-muted`;

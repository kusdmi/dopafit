/**
 * Значения `staleTime` для запросов, которым глобального дефолта мало.
 *
 * Глобальный `staleTime` в App.tsx — 30 секунд: он рассчитан на данные, которые
 * пользователь сам же и меняет (тренировки, замеры, программы), где показать
 * устаревшее на минуту было бы ошибкой.
 *
 * Справочники под это правило не подходят. Категории и каталог упражнений
 * меняются РЕЛИЗАМИ, а не действиями пользователя, поэтому 30 секунд означали
 * повторный запрос почти на каждый заход на экран — ради байт-в-байт того же
 * ответа. Поднимаем точечно в самих хуках, а не глобально: глобальный дефолт
 * защищает всё остальное и снижать его защиту нельзя.
 *
 * Полчаса выбраны как заметно больше любой сессии просмотра каталога и заметно
 * меньше 24 часов, на которые кэш и так персистится в IndexedDB
 * (PERSIST_MAX_AGE в persistQueryClient.ts). То есть свежесть после релиза
 * держится на перезапуске приложения и на истечении персиста, а не на
 * ежеминутном опросе.
 */
export const STALE_REFERENCE_DATA = 1000 * 60 * 30;
